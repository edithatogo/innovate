import doctest
import hashlib
import html
import importlib.util
import json
import os
import re
import sys
import tempfile
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = Path("docs/astro-site/src/content/docs/api/generated")
CONTRACT = Path("docs/contracts/api-documentation.json")
GENERATOR = "scripts/generate_api_reference.py"
MARKER = "<!-- Generated by scripts/generate_api_reference.py; do not edit. -->"
SOURCE_URL = "https://github.com/edithatogo/innovate/blob/main/"
ROUTE = "/innovate/api/generated/"
DEFINITIONS = (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
POLYGLOT_CHECKER = "scripts/check_polyglot_api_documentation.py"


def _sha256(data: bytes) -> str:
    """Hash exact bytes used by the generator or an output ownership record."""
    return hashlib.sha256(data).hexdigest()


def _checker() -> Any:
    """Load the sibling static checker, never the inspected numerical package."""
    path = Path(__file__).with_name("check_api_documentation.py")
    spec = importlib.util.spec_from_file_location("_innovate_api_reference_checker", path)
    if spec is None or spec.loader is None:
        raise ValueError("cannot load the API documentation checker")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _polyglot_checker() -> Any:
    """Load the bounded Julia/R source validator, never either language runtime."""
    path = Path(__file__).with_name("check_polyglot_api_documentation.py")
    spec = importlib.util.spec_from_file_location("_innovate_polyglot_reference_checker", path)
    if spec is None or spec.loader is None:
        raise ValueError("cannot load the Julia/R documentation checker")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _julia_markdown(doc: str, symbol: dict[str, Any], checker: Any) -> tuple[str, str]:
    """Retain Markdown and code blocks while nesting sections below one export."""
    body = textwrap.dedent(doc).strip()
    signature = symbol["signature"]
    match = re.match(rf"\s*{re.escape(symbol['name'])}\s*\(", body)
    if match:
        end = checker._closing(body, body.index("(", match.start()))
        if symbol["kind"] == "struct":
            signature = body[match.start() : end + 1].strip()
        body = body[end + 1 :].strip()
    rendered = []
    fence = ""
    for line in body.splitlines():
        marker = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if marker:
            if not fence:
                fence = marker[1]
            elif marker[1][0] == fence[0] and len(marker[1]) >= len(fence):
                fence = ""
        elif not fence:
            heading = re.match(r"^(#{1,6})\s+(.+)$", line)
            if heading:
                line = "#" * min(6, len(heading[1]) + 2) + " " + heading[2]
        rendered.append(line)
    return signature, "\n".join(rendered)


def _r_markdown(doc: str) -> str:
    """Render attached roxygen summaries, arguments, return values and errors."""
    tags = list(re.finditer(r"(?m)^@(\w+)\b([^\n]*)", doc))
    blocks = [_text(doc[: tags[0].start()].strip() if tags else doc.strip())]
    parameters = []
    sections = []
    for index, tag in enumerate(tags):
        body = (tag[2] + doc[tag.end() : tags[index + 1].start() if index + 1 < len(tags) else len(doc)]).strip()
        if tag[1] == "param":
            name, _, description = body.partition(" ")
            parameters.append(f"- **`{name}`**: {_text(' '.join(description.split()))}")
        elif tag[1] == "return":
            sections.append("### Returns\n\n" + _text(body))
        elif tag[1] == "section":
            title, separator, content = body.partition(":")
            if not separator:
                raise ValueError("R documentation section has no title separator")
            sections.append(f"### {_text(title)}\n\n{_text(content.strip())}")
        elif tag[1] == "examples":
            sections.append("### Examples\n\n```r\n" + body + "\n```")
        else:
            raise ValueError(f"unsupported R documentation tag: @{tag[1]}")
    if parameters:
        blocks.append("### Arguments\n\n" + "\n".join(parameters))
    return "\n\n".join([*blocks, *sections])


def _polyglot_pages(root: Path, languages: list[str]) -> tuple[dict[str, str], dict[str, Any]]:
    """Render exactly the currently validated exports and fingerprint their inputs."""
    checker = _polyglot_checker()
    inventory = checker.build_inventory(root)
    recorded_path = root / checker.INVENTORY
    recorded = recorded_path.read_text(encoding="utf-8")
    if recorded != checker.render_inventory(inventory):
        raise ValueError("stale or modified Julia/R structural inventory; refresh it after source review")
    pages = {}
    metadata: dict[str, Any] = {
        "inventory": checker.INVENTORY,
        "inventory_sha256": _sha256(recorded_path.read_bytes()),
        "inputs": inventory["sources"],
        "languages": {},
        "sources": {},
    }
    for language in languages:
        symbols = inventory["symbols"][language]
        if not symbols or len({symbol["name"] for symbol in symbols}) != len(symbols):
            raise ValueError(f"empty or duplicate {language} public inventory")
        label = "Julia" if language == "julia" else "R"
        content = [
            _frontmatter(
                f"Current {label} API", f"Source-derived reference for all {len(symbols)} public {label} exports."
            ),
            f"This page renders every exported {label} symbol in the validated native binding inventory. "
            "Signatures and documentation come from the same checked source. "
            "Source links point to the moving `main` branch; hashes identify the exact inputs.",
            "The binding calls the Rust kernel through the native C ABI. Generation does not load "
            "the native library or execute examples. Native language execution and scientific review "
            "are separate qualification requirements.",
            f"[Python reference]({ROUTE}) · [Julia reference]({ROUTE}julia/) · [R reference]({ROUTE}r/)",
            "## Public exports\n\n" + "\n".join(f"- [`{item['name']}`](#{item['name'].lower()})" for item in symbols),
        ]
        rendered = []
        anchors = set()
        for symbol in symbols:
            source = checker._read(root, symbol["source"])
            if f"sha256:{checker._sha(source)}" != inventory["sources"][symbol["source"]]:
                raise ValueError("binding source changed while generating its reference")
            offset = sum(len(line) for line in source.splitlines(keepends=True)[: symbol["source_line"] - 1])
            if language == "julia":
                _, docs = checker._mask(source)
                attached = [doc for _, end, doc in docs if end <= offset and not source[end:offset].strip()]
                if len(attached) != 1 or checker._sha(attached[0]) != symbol["documentation_sha256"]:
                    raise ValueError(f"{symbol['name']}: Julia source documentation changed")
                signature, body = _julia_markdown(attached[0], symbol, checker)
            else:
                doc = checker._roxygen(source, offset)
                if checker._sha(doc) != symbol["source_documentation_sha256"]:
                    raise ValueError(f"{symbol['name']}: R source documentation changed")
                signature, body = symbol["signature"], _r_markdown(doc)
            anchor = symbol["name"].lower()
            if anchor in anchors:
                raise ValueError(f"{language} exported names collide at a rendered anchor")
            anchors.add(anchor)
            digest = _sha256((root / symbol["source"]).read_bytes())
            metadata["sources"][symbol["source"]] = digest
            content.extend(
                [
                    f"## `{symbol['name']}`",
                    _source({"path": symbol["source"], "line": symbol["source_line"]}, digest),
                    f"### Signature\n\n```{language}\n{signature}\n```",
                    body,
                ]
            )
            if language == "r":
                content.append(f"[R help source]({SOURCE_URL}{symbol['documentation']})")
            rendered.append(f"{symbol['source']}::{symbol['name']}")
        if len(rendered) != len(symbols) or len(set(rendered)) != len(symbols):
            raise ValueError(f"{language} rendered inventory does not match validated exports")
        pages[f"{language}.md"] = "\n\n".join(content).rstrip() + "\n"
        metadata["languages"][language] = {
            "symbol_count": len(rendered),
            "page_count": 1,
            "public_symbols": sorted(rendered),
            "execution_status": "not_run_by_generator",
        }
    return pages, metadata


def _nodes(tree: ast.Module, module: str) -> dict[str, ast.AST]:
    """Map source-qualified definitions including methods and nested classes."""
    result: dict[str, ast.AST] = {module: tree}

    def visit(node: ast.AST, name: str) -> None:
        """Preserve enclosing names while walking structural containers."""
        for child in ast.iter_child_nodes(node):
            child_name = f"{name}.{child.name}" if isinstance(child, DEFINITIONS) else name
            if isinstance(child, DEFINITIONS):
                if child_name in result:
                    raise ValueError(f"ambiguous source definition: {child_name}")
                result[child_name] = child
            visit(child, child_name)

    visit(tree, module)
    return result


def _text(value: str) -> str:
    """Render common docstring roles as inline code and escape raw HTML."""
    value = re.sub(r":(?:func|class|meth|mod|attr|obj):`([^`]+)`", r"`\1`", value)
    value = re.sub(r"``([^`]+)``", r"`\1`", value)
    return html.escape(value, quote=False)


def _example_markdown(body: str) -> str:
    """Display doctest statements as copyable Python, retaining expected outputs."""
    pieces = doctest.DocTestParser().parse(body)
    blocks: list[str] = []
    code: list[str] = []

    def flush() -> None:
        """Close a contiguous example block before explanatory prose."""
        if code:
            blocks.append("```python\n" + "".join(code).rstrip() + "\n```")
            code.clear()

    for piece in pieces:
        if isinstance(piece, doctest.Example):
            code.append(piece.source)
            if piece.want:
                code.extend(f"# Expected: {line}\n" for line in piece.want.rstrip().splitlines())
        elif piece.strip():
            flush()
            blocks.append(_text(piece.strip()))
    flush()
    return "\n\n".join(blocks) if blocks else _text(body)


def _doc_markdown(doc: str, checker: Any, level: int = 2) -> str:
    """Render Google or NumPy sections without discarding explanatory text."""
    lines = doc.splitlines()
    starts = [
        index
        for index, line in enumerate(lines)
        if line == line.lstrip()
        and (
            re.fullmatch(r"[A-Za-z][A-Za-z /-]*:", line)
            or (line and index + 1 < len(lines) and re.fullmatch(r"-{3,}", lines[index + 1].strip()))
        )
    ]
    preamble = "\n".join(lines[: starts[0] if starts else len(lines)]).strip()
    blocks = [_text(preamble)] if preamble else []
    sections = checker._sections(doc)
    if len(sections) != len(starts):
        raise ValueError("duplicate docstring section headings cannot be rendered losslessly")
    for name, section in sections.items():
        _, body = section
        blocks.append(f"{'#' * level} {name.title()}")
        if name in {"parameters", "attributes", "raises"}:
            entries = checker._entries(section)
            if not entries:
                raise ValueError(f"cannot render documented {name} entries")
            blocks.append("\n".join(f"- **`{key}`**: {_text(description)}" for key, description in entries.items()))
        elif name in {"examples", "example"}:
            blocks.append(_example_markdown(body))
        else:
            blocks.append(_text(body))
    return "\n\n".join(blocks)


def _signature(node: ast.AST) -> str:
    """Render declared types, defaults and supported decorators from syntax."""
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
        signature = f"{prefix} {node.name}({ast.unparse(node.args)})"
        if node.returns is not None:
            signature += f" -> {ast.unparse(node.returns)}"
        if len(signature) > 100:
            parameters = []
            positional = [*node.args.posonlyargs, *node.args.args]
            first_default = len(positional) - len(node.args.defaults)
            for index, argument in enumerate(positional):
                rendered = ast.unparse(argument)
                if index >= first_default:
                    rendered += " = " + ast.unparse(node.args.defaults[index - first_default])
                parameters.append(rendered)
                if index + 1 == len(node.args.posonlyargs):
                    parameters.append("/")
            if node.args.vararg:
                parameters.append("*" + ast.unparse(node.args.vararg))
            elif node.args.kwonlyargs:
                parameters.append("*")
            for argument, default in zip(node.args.kwonlyargs, node.args.kw_defaults, strict=True):
                rendered = ast.unparse(argument)
                if default is not None:
                    rendered += " = " + ast.unparse(default)
                parameters.append(rendered)
            if node.args.kwarg:
                parameters.append("**" + ast.unparse(node.args.kwarg))
            signature = f"{prefix} {node.name}(\n" + "".join(f"    {item},\n" for item in parameters) + ")"
            if node.returns is not None:
                signature += f" -> {ast.unparse(node.returns)}"
        decorators = [f"@{ast.unparse(item)}" for item in node.decorator_list]
        return "\n".join([*decorators, signature + ": ..."])
    if isinstance(node, ast.ClassDef):
        decorators = [f"@{ast.unparse(item)}" for item in node.decorator_list]
        bases = [ast.unparse(base) for base in node.bases]
        bases.extend(ast.unparse(keyword) for keyword in node.keywords)
        header = f"class {node.name}" + (f"({', '.join(bases)})" if bases else "") + ":"
        attributes = [
            f"    {ast.unparse(child)}"
            for child in node.body
            if isinstance(child, ast.AnnAssign)
            and isinstance(child.target, ast.Name)
            and not child.target.id.startswith("_")
        ]
        return "\n".join([*decorators, header, *(attributes or ["    ..."])])
    raise ValueError("only classes and callables have rendered signatures")


def _frontmatter(title: str, description: str) -> str:
    """Use JSON-quoted YAML scalars so names cannot alter page metadata."""
    return (
        f"---\ntitle: {json.dumps(title)}\ndescription: {json.dumps(description)}\n"
        f"generated_by: {json.dumps(GENERATOR)}\n---\n\n{MARKER}"
    )


def _source(symbol: dict[str, Any], digest: str) -> str:
    """Link the moving main branch while recording the exact source-file digest."""
    path = symbol["path"]
    return f"[View source]({SOURCE_URL}{path}#L{symbol['line']}) · Source file SHA-256: `{digest}`"


def _slug(value: str) -> str:
    """Create stable readable filenames, rejecting empty or reserved slugs."""
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", value)
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    if not slug or slug in {"index", "manifest"}:
        raise ValueError(f"public symbol has a reserved or empty page slug: {value}")
    return slug


def build_artifacts(root: Path) -> dict[str, str]:
    """Build all expected pages and their manifest in memory, without writing.

    Keys are repository-relative paths. The static API checker must establish
    complete Python documentation before any content can be generated. Enabled
    Julia/R pages also require the exact validated polyglot source inventory. The
    resulting reference does not qualify Rust, examples or scientific validity.
    """
    root = root.resolve()
    checker = _checker()
    contract_bytes = (root / CONTRACT).read_bytes()
    contract = json.loads(contract_bytes)
    languages = contract.get("generated_reference_languages")
    if languages not in (["python"], ["python", "julia", "r"]):
        raise ValueError("generated_reference_languages must explicitly be ['python'] or ['python', 'julia', 'r']")
    report = checker.audit(root, contract)
    if not report["python_complete"]:
        details = "; ".join(gap["id"] for gap in report["gaps"][:8])
        raise ValueError(f"API source documentation is incomplete: {details}")
    public = [symbol for symbol in report["symbols"] if symbol["exposure"] == "public"]
    modules = [symbol for symbol in public if symbol["kind"] == "module"]
    if not modules or not any(symbol["kind"] != "module" for symbol in public):
        raise ValueError("public API scope is empty; refusing an empty reference")
    node_map: dict[str, ast.AST] = {}
    for module in modules:
        nodes = _nodes(ast.parse((root / module["path"]).read_bytes()), module["name"])
        node_map.update({f"{module['path']}::{name}": node for name, node in nodes.items()})
        tree = nodes[module["name"]]
        for child in tree.body:
            if isinstance(child, (ast.Assign, ast.AnnAssign)):
                targets = child.targets if isinstance(child, ast.Assign) else [child.target]
                if any(isinstance(target, ast.Name) and target.id == "__all__" for target in targets):
                    for export in ast.literal_eval(child.value):
                        target = nodes.get(f"{module['name']}.{export}")
                        if not isinstance(target, DEFINITIONS):
                            raise ValueError(f"export has no documented renderable definition: {export}")
    missing = [symbol["id"] for symbol in public if symbol["id"] not in node_map]
    if missing:
        raise ValueError(f"public inventory contains unrenderable symbols: {missing}")

    artifacts: dict[str, str] = {}
    page_symbols: dict[str, list[str]] = {"index.md": [module["id"] for module in modules]}
    index = [
        _frontmatter("Current Python API", "Source-generated reference for the current native Python API."),
        "This reference is generated from the documented Python source. Signatures, "
        "parameters, returns, errors and class members come from the same checkout. "
        "Generation does not import the numerical runtime or execute examples.",
        "Source links point to the moving `main` branch. The source-file SHA-256 "
        "values below and the generated manifest identify the exact input bytes.",
    ]
    table = ["## Public definitions\n", "| Symbol | Purpose |", "| --- | --- |"]
    covered = set(page_symbols["index.md"])
    for module in modules:
        top_level = [
            symbol
            for symbol in public
            if symbol["path"] == module["path"]
            and symbol["name"].startswith(module["name"] + ".")
            and "." not in symbol["name"][len(module["name"]) + 1 :]
        ]
        for symbol in top_level:
            node = node_map[symbol["id"]]
            short_name = symbol["name"].split(".")[-1]
            slug_source = short_name if module["name"] == "innovate" else symbol["name"]
            slug = _slug(slug_source)
            filename = f"{slug}.md"
            if filename in page_symbols:
                raise ValueError(f"public symbols collide at page {filename}")
            doc = ast.get_docstring(node) or ""
            summary = doc.splitlines()[0]
            table.append(f"| [`{symbol['name']}`]({ROUTE}{slug}/) | {_text(summary).replace('|', r'\|')} |")
            content = [
                _frontmatter(symbol["name"], summary),
                f"[All current Python definitions]({ROUTE})",
                _source(symbol, report["files"][symbol["path"]]),
                "## Signature\n\n```python\n" + _signature(node) + "\n```",
                _doc_markdown(doc, checker),
            ]
            included = [symbol["id"]]
            descendants = [
                member
                for member in public
                if member["path"] == symbol["path"] and member["name"].startswith(symbol["name"] + ".")
            ]
            for member in descendants:
                member_node = node_map[member["id"]]
                name = member["name"][len(symbol["name"]) + 1 :]
                content.extend(
                    [
                        f"## `{name}`",
                        _source(member, report["files"][member["path"]]),
                        "```python\n" + _signature(member_node) + "\n```",
                        _doc_markdown(ast.get_docstring(member_node) or "", checker, level=3),
                    ]
                )
                included.append(member["id"])
            artifacts[(DEFAULT_OUTPUT / filename).as_posix()] = "\n\n".join(content).rstrip() + "\n"
            page_symbols[filename] = included
            covered.update(included)
    if covered != {symbol["id"] for symbol in public}:
        raise ValueError("generated pages do not cover the complete public inventory")
    index.append("\n".join(table))
    for module in modules:
        index.extend(
            [
                f"## Package `{module['name']}`",
                _source(module, report["files"][module["path"]]),
                _doc_markdown(ast.get_docstring(node_map[module["id"]]) or "", checker, level=3),
            ]
        )
    index.append(
        f"## Generation scope\n\n{len(public)} public source symbols are rendered from "
        f"{len(report['files'])} inventoried Python source files. Private and nested "
        "helpers are checked for documentation but do not appear as public API pages."
    )
    language_metadata = {
        "python": {
            "symbol_count": len(covered),
            "page_count": len(page_symbols),
            "public_symbols": sorted(covered),
            "execution_status": "not_run_by_generator",
        }
    }
    sources = dict(report["files"])
    polyglot_metadata = None
    if languages != ["python"]:
        extra_pages, polyglot_metadata = _polyglot_pages(root, languages[1:])
        for filename, content in extra_pages.items():
            if filename in page_symbols:
                raise ValueError(f"language reference collides with a Python symbol page: {filename}")
            language = Path(filename).stem
            artifacts[(DEFAULT_OUTPUT / filename).as_posix()] = content
            page_symbols[filename] = polyglot_metadata["languages"][language]["public_symbols"]
        language_metadata.update(polyglot_metadata.pop("languages"))
        sources.update(polyglot_metadata.pop("sources"))
        index.append(
            "## Other current bindings\n\n"
            f"- [Julia public API]({ROUTE}julia/)\n"
            f"- [R public API]({ROUTE}r/)\n\n"
            "These grouped references have their own source inventories. Python example execution "
            "does not establish Julia or R runtime qualification."
        )
    artifacts[(DEFAULT_OUTPUT / "index.md").as_posix()] = "\n\n".join(index).rstrip() + "\n"
    manifest = {
        "schema_version": 1,
        "generator": GENERATOR,
        "generator_sha256": _sha256(Path(__file__).read_bytes()),
        "checker_sha256": _sha256(Path(__file__).with_name("check_api_documentation.py").read_bytes()),
        "contract_sha256": _sha256(contract_bytes),
        "source_ref": "main",
        "sources": sources,
        "public_symbols": sorted(covered),
        "languages": language_metadata,
        "pages": {
            filename: {
                "sha256": _sha256(artifacts[(DEFAULT_OUTPUT / filename).as_posix()].encode()),
                "symbols": sorted(symbols),
                "language": Path(filename).stem if filename in {"julia.md", "r.md"} and polyglot_metadata else "python",
            }
            for filename, symbols in sorted(page_symbols.items())
        },
    }
    if polyglot_metadata is not None:
        manifest["polyglot"] = polyglot_metadata
    artifacts[(DEFAULT_OUTPUT / "manifest.json").as_posix()] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    return dict(sorted(artifacts.items()))


def _output_directory(root: Path) -> Path:
    """Reject symlinked output ancestors and non-directory output surfaces."""
    root = root.resolve()
    path = root
    for part in DEFAULT_OUTPUT.parts:
        path = path / part
        if path.is_symlink() or (path.exists() and not path.is_dir()):
            raise ValueError(f"unsafe generated output directory: {path}")
    return path


def _owned_pages(output: Path) -> dict[str, Any]:
    """Validate the previous manifest before trusting its file membership."""
    path = output / "manifest.json"
    if path.is_symlink():
        raise ValueError("generated manifest must not be a symlink")
    if not path.exists():
        return {}
    if not path.is_file():
        raise ValueError("generated manifest is not a regular file")
    manifest = json.loads(path.read_text(encoding="utf-8"))
    if (
        not isinstance(manifest, dict)
        or manifest.get("schema_version") != 1
        or manifest.get("generator") != GENERATOR
        or not isinstance(manifest.get("pages"), dict)
        or "index.md" not in manifest["pages"]
    ):
        raise ValueError("unrecognized generated API manifest; preserving existing files")
    for name, entry in manifest["pages"].items():
        if (
            not re.fullmatch(r"[a-z0-9][a-z0-9-]*\.md", name)
            or not isinstance(entry, dict)
            or not isinstance(entry.get("sha256"), str)
            or not re.fullmatch(r"[a-f0-9]{64}", entry["sha256"])
        ):
            raise ValueError("unsafe generated manifest file membership")
        page = output / name
        if page.is_symlink() or (page.exists() and not page.is_file()):
            raise ValueError(f"unsafe generated page: {name}")
        if page.exists():
            raw = page.read_bytes()
            if MARKER.encode() not in raw or _sha256(raw) != entry["sha256"]:
                raise ValueError(f"generated page was modified; preserving {name}")
    return manifest["pages"]


def check_generated(root: Path) -> list[str]:
    """Return missing, stale or unsafe output errors without modifying files."""
    root = root.resolve()
    expected = build_artifacts(root)
    try:
        output = _output_directory(root)
        _owned_pages(output)
    except (OSError, ValueError) as error:
        return [str(error)]
    errors = []
    for relative, content in expected.items():
        path = root / relative
        if path.is_symlink() or not path.is_file():
            errors.append(f"missing or unsafe generated artifact: {relative}")
        elif path.read_bytes() != content.encode():
            errors.append(f"stale generated artifact: {relative}")
    return errors


def generate(root: Path) -> dict[str, int]:
    """Write deterministic artifacts and remove only unchanged owned stale pages."""
    root = root.resolve()
    expected = build_artifacts(root)
    output = _output_directory(root)
    previous = _owned_pages(output)
    names = {Path(relative).name for relative in expected}
    for name in names - {"manifest.json"}:
        path = output / name
        if path.is_symlink() or (path.exists() and name not in previous):
            raise ValueError(f"refusing to overwrite unowned generated-output path: {name}")
    output.mkdir(parents=True, exist_ok=True)
    # Publish the manifest last so readers never accept a new manifest for old pages.
    ordered = sorted(expected, key=lambda path: (path.endswith("/manifest.json"), path))
    for relative in ordered:
        destination = root / relative
        descriptor, temporary = tempfile.mkstemp(prefix=".api-generation-", dir=output)
        try:
            with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(expected[relative])
            os.replace(temporary, destination)
        finally:
            Path(temporary).unlink(missing_ok=True)
    removed = 0
    for name in sorted(set(previous) - names):
        path = output / name
        if path.exists():
            if path.is_symlink() or _sha256(path.read_bytes()) != previous[name]["sha256"]:
                raise ValueError(f"refusing to remove modified generated page: {name}")
            path.unlink()
            removed += 1
    return {"pages": len(expected) - 1, "removed": removed}


def main(argv: list[str] | None = None) -> int:
    """Generate the reference, or verify a prior build with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check exact generated content without writing.")
    args = parser.parse_args(argv)
    try:
        if args.check:
            errors = check_generated(ROOT)
            if errors:
                for error in errors:
                    print(error, file=sys.stderr)
                return 1
            print("Current API references match all declared language, source and generator hashes.")
        else:
            result = generate(ROOT)
            pages, removed = result["pages"], result["removed"]
            print(f"Generated {pages} current API reference pages; removed {removed} owned stale pages.")
    except (OSError, ValueError, SyntaxError) as error:
        print(f"API reference generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
