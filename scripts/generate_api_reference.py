"""Generate current binding API pages from source without importing the runtime.

The documentation checker defines the public inventory. Generation fails closed
on inventory or docstring gaps, and the manifest binds pages to source, generator
and checker hashes. Only unchanged files owned by a previous valid manifest may
be overwritten or removed; unrelated files are never cleaned up automatically.
"""

from __future__ import annotations

